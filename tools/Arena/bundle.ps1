# Builds a self-contained arena bundle for another Windows machine (no .NET needed there):
#   app\        Arena.exe and its runtime, with data\cards.csv and data\npc-decks.csv
#   scenarios.json
#   run.ps1     starts the run at BelowNormal priority, writing results\*.jsonl and run.log
#   manifest.json  commit, dirty flag, arguments and input hashes, so a result can be traced
# Usage: tools\Arena\bundle.ps1 -Out <folder> -Scenarios <scenarios.json> -RunArgs 'games=200 policies=baseline,surewin opponents=softmax:2,minimax'
param(
    [Parameter(Mandatory)] [string]$Out,
    [Parameter(Mandatory)] [string]$Scenarios,
    [string]$RunArgs = 'games=20',
    [int]$Shards = 1,
    # Solver threads per game (Chaos openings need several); games per shard = cores / shards / inner.
    [int]$Inner = 1
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
New-Item -ItemType Directory -Force -Path $Out | Out-Null
$Out = (Resolve-Path $Out).Path

dotnet publish (Join-Path $PSScriptRoot 'Arena.csproj') -c Release -r win-x64 --self-contained true -p:PublishSingleFile=false -o (Join-Path $Out 'app') | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'publish failed' }

$data = Join-Path $Out 'app\data'
New-Item -ItemType Directory -Force -Path $data | Out-Null
Copy-Item (Join-Path $repo 'research\data\cards.csv'), (Join-Path $repo 'research\data\npc-decks.csv') $data
Copy-Item $Scenarios (Join-Path $Out 'scenarios.json')

# One process per shard, each on its share of the cores; results\shard-k.jsonl resumes on rerun.
$run = @"
# Generated by tools\Arena\bundle.ps1. Rerun to resume: finished games are skipped.
`$ErrorActionPreference = 'Stop'
Set-Location `$PSScriptRoot
New-Item -ItemType Directory -Force -Path results | Out-Null
`$shards = $Shards
`$inner = $Inner
`$threads = [Math]::Max(1, [Math]::Floor(([Environment]::ProcessorCount - 2) / `$shards / `$inner))
`$procs = @()
for (`$k = 0; `$k -lt `$shards; `$k++) {
    `$p = Start-Process -FilePath 'app\Arena.exe' -PassThru -NoNewWindow ``
        -ArgumentList @('run', 'scenarios=scenarios.json', "shard=`$k/`$shards", "threads=`$threads", "inner=`$inner", "out=results\shard-`$k.jsonl", $(($RunArgs -split ' ' | ForEach-Object { "'$_'" }) -join ', ')) ``
        -RedirectStandardOutput "results\shard-`$k.log" -RedirectStandardError "results\shard-`$k.err"
    `$p.PriorityClass = 'BelowNormal'
    `$procs += `$p
    "shard `$k pid `$(`$p.Id)" | Tee-Object -FilePath run.log -Append
}

# Stay until every shard ends: over SSH the shards live only as long as this session.
`$procs | Wait-Process
"all shards done `$(Get-Date -Format o)" | Tee-Object -FilePath run.log -Append
"@
Set-Content -Path (Join-Path $Out 'run.ps1') -Value $run -Encoding utf8

$commit = git -C $repo rev-parse HEAD
$dirty = [bool](git -C $repo status --porcelain -- TrialHater.Core tools/Arena)
$hash = { param($f) (Get-FileHash $f -Algorithm SHA256).Hash.Substring(0, 16) }
[ordered]@{
    created = (Get-Date).ToUniversalTime().ToString('o')
    commit = $commit
    dirtyCoreOrArena = $dirty
    runArgs = $RunArgs
    shards = $Shards
    inner = $Inner
    inputs = [ordered]@{
        'scenarios.json' = & $hash (Join-Path $Out 'scenarios.json')
        'cards.csv' = & $hash (Join-Path $data 'cards.csv')
        'npc-decks.csv' = & $hash (Join-Path $data 'npc-decks.csv')
    }
} | ConvertTo-Json | Set-Content -Path (Join-Path $Out 'manifest.json') -Encoding utf8

"bundle ready: $Out"
